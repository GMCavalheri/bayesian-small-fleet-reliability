"""Phase 3: does NUTS reproduce the exact posterior? Marginal and centred models.

Writes ``results/hierarchical_mcmc.md``. NUTS trajectories depend on floating-point details
of the compiled model, so this file is regenerated by the reproduce job but **not** compared
byte for byte; what must hold everywhere (agreement with the oracle within Monte Carlo
error, R-hat, ESS) is enforced by ``tests/test_hierarchical_model.py``.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

from smallfleet.hierarchical_model import (
    AlphaBetaHyperprior,
    MeanCVHyperprior,
    exact_posterior,
)
from smallfleet.hierarchical_model.model import sample

from common import table, write_result

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tests"))
from nureg import example_8_1  # noqa: E402

SEED = 20261123
DRAWS = TUNE = 2000


def compare(label, x, t, prior, units) -> tuple[list[list[object]], list[list[object]]]:
    exact = exact_posterior(x, t, prior)
    diag, est = [], []
    for marginal in (True, False):
        r = sample(x, t, prior, marginal=marginal, draws=DRAWS, tune=TUNE, seed=SEED)
        form = "marginal" if marginal else "centred"
        diag.append(
            [
                label,
                form,
                f"{r.rhat_max:.3f}",
                f"{r.ess_bulk_min:.0f}",
                f"{r.ess_tail_min:.0f}",
                r.divergences,
            ]
        )
        for name, i in units:
            lo, hi = r.unit_interval(i)
            elo, ehi = exact.unit_interval(i)
            z = (r.unit_mean(i) - exact.unit_mean(i)) / r.unit_mcse(i)
            est.append(
                [
                    label,
                    form,
                    name,
                    f"{exact.unit_mean(i):.3g} ({elo:.3g}, {ehi:.3g})",
                    f"{r.unit_mean(i):.3g} ({lo:.3g}, {hi:.3g})",
                    f"{z:+.1f}",
                ]
            )
    return diag, est


def main() -> None:
    names, x, t = example_8_1()
    d1, e1 = compare(
        "NUREG Example 8.1",
        x,
        t,
        AlphaBetaHyperprior(),
        [(p, names.index(p)) for p in ("Callaway", "Grand Gulf", "Oconee 2")],
    )
    sx = np.array([0, 1, 0, 2, 1, 4])
    st = np.array([2, 3, 4, 6, 8, 12]) * 35 * 12 / 1000
    d2, e2 = compare(
        "6 sparse operators",
        sx,
        st,
        MeanCVHyperprior(mean_median=0.2, mean_log_sd=1.0, cv_scale=1.0),
        [("operator 1 (0 events)", 0), ("operator 6 (4 events)", 5)],
    )
    write_result(
        "hierarchical_mcmc",
        "Phase 3: NUTS against the exact posterior",
        [
            (
                "Setup",
                f"PyMC NUTS, 4 chains × {DRAWS} draws after {TUNE} tuning steps, one core, "
                f"seed {SEED}, target_accept 0.95. Marginal form: rates integrated out, then "
                "drawn exactly from their conditionals. Centred form: rates sampled as "
                "parameters. The sparse dataset is 6 operators of 2-12 business jets with "
                "counts (0, 1, 0, 2, 1, 4) in one year, hyperprior μ ~ LogNormal(log 0.2, 1), "
                "cv ~ HalfNormal(1). Not byte-reproducible across machines (see the script).\n",
            ),
            (
                "Diagnostics",
                table(
                    ["data", "form", "max R-hat", "min bulk ESS", "min tail ESS", "divergences"],
                    d1 + d2,
                ),
            ),
            (
                "Estimates: exact against NUTS",
                "z is (NUTS mean − exact mean) / MCSE; |z| < 4 is expected.\n\n"
                + table(
                    ["data", "form", "unit", "exact mean (90 %)", "NUTS mean (90 %)", "z"], e1 + e2
                ),
            ),
        ],
    )


if __name__ == "__main__":
    main()
